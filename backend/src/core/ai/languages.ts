const byCode = new Map<string, LanguageOption>();
for (const language of RAW_LANGUAGES) {
  if (!byCode.has(language.code)) {
    byCode.set(language.code, language);
  }
}

export const SUPPORTED_LANGUAGES: LanguageOption[] = Array.from(byCode.values());
export const DEFAULT_LANGUAGE = 'ar';

export function getLanguage(code: string | undefined): LanguageOption {
  const clean = (code || '').trim();
  if (byCode.has(clean)) return byCode.get(clean)!;
  // Tolerate legacy regional tags such as ar-EG / en-US.
  const base = clean.split('-')[0];
  if (byCode.has(base)) return byCode.get(base)!;
  return byCode.get(DEFAULT_LANGUAGE)!;
}

export function isRtlLanguage(code: string | undefined): boolean {
  return Boolean(getLanguage(code).rtl);
}
